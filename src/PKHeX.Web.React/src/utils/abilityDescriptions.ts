function normalizeKey(str: string): string {
  return str.toLowerCase().replace(/[^a-z0-9]/g, '')
}

/**
 * Retorna a descrição detalhada da habilidade por ID ou Nome.
 */
export function getAbilityDescription(
  abilityId: number,
  abilityName: string,
  t?: (key: string, fallback?: string) => string,
): string {
  const normalized = normalizeKey(abilityName)
  const description = descriptionsPt[normalized]

  if (description) {
    return description
  }

  const fallbackText = t
    ? t(
        'ability.fallback',
        'Habilidade passiva especial que concede efeitos em combate ou exploração.',
      )
    : 'Habilidade passiva especial que concede efeitos em combate ou exploração.'

  return fallbackText
}
